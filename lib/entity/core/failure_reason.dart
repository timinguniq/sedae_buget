/// 도메인 계약이 말하는 실패 이유. 호출부는 이 값으로 분기한다.
/// HTTP 상태코드·전송 계층 사정은 data 레이어에서 이 값으로 번역되고 여기서 끝난다.
enum FailureReason {
  /// 세션이 없거나 만료됐다.
  unauthorized,

  /// 로그인은 됐지만 허용되지 않는다(기본 분류 수정 등).
  forbidden,

  /// 요청한 것이 서버에 없다.
  notFound,

  /// 이미 있는 것과 부딪혔다(이름 중복 등).
  conflict,

  /// 보낸 값이 규칙에 맞지 않는다.
  invalid,

  /// 네트워크에 닿지 못했다.
  offline,

  /// 응답을 기다리다 시간이 지났다.
  timeout,

  /// 서버가 처리하지 못했다.
  server,

  /// 분류되지 않은 실패.
  unknown,
}
